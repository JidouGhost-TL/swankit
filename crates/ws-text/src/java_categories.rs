pub(crate) fn java_letter_or_digit_below_3000(c: char) -> bool {
    if c >= '\u{3000}' {
        return false;
    }
    let value = c as u16;
    let index = JAVA_LETTER_OR_DIGIT_BELOW_3000.partition_point(|&(_, end)| end < value);
    JAVA_LETTER_OR_DIGIT_BELOW_3000
        .get(index)
        .is_some_and(|&(start, _)| start <= value)
}
